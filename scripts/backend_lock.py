"""Write and verify the backend runtime lock.

The lock is the exact, marker- and extra-aware closure of the dependencies declared in
app/backend/pyproject.toml. It is committed so that a clean clone, a developer virtualenv and the
release build resolve the same versions. It deliberately contains no development tooling.

Usage:
    python scripts/backend_lock.py --check
    python scripts/backend_lock.py --write

Run it with the backend virtualenv interpreter, which has the installed distributions and the
``packaging`` library.
"""
from __future__ import annotations

import argparse
import importlib.metadata
import re
import sys
import tomllib
from pathlib import Path

try:
    from packaging.markers import default_environment
    from packaging.requirements import Requirement
except ImportError as exc:  # pragma: no cover - the virtualenv always has packaging
    raise SystemExit(f"packaging is required: {exc}")

LOCK_PATH = Path("app/backend/requirements-runtime.lock")
PYPROJECT_PATH = Path("app/backend/pyproject.toml")
HEADER = [
    "# CreatorOS backend runtime lock -- generated by scripts/backend_lock.py.",
    "# Exact closure of [project].dependencies for Windows x64 / CPython 3.12.",
    "# Development and test dependencies are intentionally absent.",
]


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _installed() -> dict[str, importlib.metadata.Distribution]:
    distributions: dict[str, importlib.metadata.Distribution] = {}
    for dist in importlib.metadata.distributions():
        name = dist.metadata.get("Name")
        if not name:
            continue
        canonical = normalize(name)
        existing = distributions.get(canonical)
        if existing is not None and existing.version != dist.version:
            raise SystemExit(
                f"two versions of {canonical} are installed: {existing.version} and {dist.version}"
            )
        distributions[canonical] = dist
    return distributions


def _applies(requirement: Requirement, extras: set[str]) -> bool:
    if requirement.marker is None:
        return True
    environment = default_environment()
    for extra in sorted(extras or {""}):
        environment["extra"] = extra
        if requirement.marker.evaluate(environment):
            return True
    return False


def compute_closure(pyproject: dict, distributions: dict) -> dict[str, str]:
    project = pyproject.get("project") or {}
    requirements = project.get("dependencies") or []
    if not isinstance(requirements, list) or not requirements:
        raise SystemExit("pyproject.toml declares no runtime dependencies")
    requested: dict[str, set[str]] = {}
    queue: list[str] = []
    for text in requirements:
        requirement = Requirement(str(text))
        name = normalize(requirement.name)
        requested.setdefault(name, set()).update(requirement.extras)
        queue.append(name)
    seen: set[str] = set()
    while queue:
        name = queue.pop()
        if name in seen:
            continue
        seen.add(name)
        dist = distributions.get(name)
        if dist is None:
            continue
        extras = requested.get(name, set())
        for text in dist.requires or []:
            requirement = Requirement(str(text))
            if not _applies(requirement, extras):
                continue
            target = normalize(requirement.name)
            before = set(requested.get(target, set()))
            requested.setdefault(target, set()).update(requirement.extras)
            if target not in seen or requested[target] != before:
                queue.append(target)
    missing = sorted(name for name in seen if name not in distributions)
    if missing:
        raise SystemExit("runtime dependencies are not installed: " + ", ".join(missing))
    return {name: distributions[name].version for name in sorted(seen)}


def render(versions: dict[str, str]) -> str:
    lines = list(HEADER)
    lines.extend(f"{name}=={version}" for name, version in sorted(versions.items()))
    return "\n".join(lines) + "\n"


def parse_lock(text: str) -> dict[str, str]:
    versions: dict[str, str] = {}
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9_.-]*)==([^\s]+)", line)
        if match is None:
            raise ValueError(f"line {number} is not a name==version pin: {raw!r}")
        name = normalize(match.group(1))
        if name in versions:
            raise ValueError(f"duplicate pin for {name} on line {number}")
        versions[name] = match.group(2)
    return versions


def read_lock(path: Path) -> dict[str, str]:
    return parse_lock(path.read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the lock from this environment")
    mode.add_argument("--check", action="store_true", help="verify the lock matches this environment")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(argv)
    root = args.root.resolve()
    pyproject_path = root / PYPROJECT_PATH
    lock_path = root / LOCK_PATH
    pyproject = tomllib.loads(pyproject_path.read_text(encoding="utf-8"))
    versions = compute_closure(pyproject, _installed())
    rendered = render(versions)
    if args.write:
        lock_path.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {lock_path} ({len(versions)} runtime distributions)")
        return 0
    if not lock_path.is_file():
        print(f"missing runtime lock: {lock_path}", file=sys.stderr)
        return 1
    committed = read_lock(lock_path)
    if committed == versions:
        print(f"runtime lock matches ({len(versions)} distributions)")
        return 0
    missing = sorted(set(versions) - set(committed))
    extra = sorted(set(committed) - set(versions))
    changed = sorted(
        f"{name}: {committed[name]} -> {versions[name]}"
        for name in set(committed) & set(versions)
        if committed[name] != versions[name]
    )
    print("runtime lock does not match the installed environment", file=sys.stderr)
    for label, items in (("missing", missing), ("extra", extra), ("changed", changed)):
        if items:
            print(f"  {label}: " + ", ".join(items), file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())